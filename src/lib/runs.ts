/**
 * Persistence + export helpers for analysis runs.
 *
 * Saving is best-effort: an unavailable database must never break an analysis,
 * so `saveRun` swallows errors (after logging) and returns null. Export helpers
 * flatten each run kind into CSV rows and a Markdown research report.
 */
import { desc, eq } from "drizzle-orm";
import { db } from "@/db";
import { runs, type NewRun, type Run } from "@/db/schema";
import { log } from "./log";

export async function saveRun(run: NewRun): Promise<string | null> {
  try {
    const [row] = await db.insert(runs).values(run).returning({ id: runs.id });
    return row?.id ?? null;
  } catch (err) {
    log.warn("run not saved (database unavailable?)", { error: (err as Error).message });
    return null;
  }
}

export async function listRuns(limit = 200): Promise<Run[]> {
  try {
    return await db.select().from(runs).orderBy(desc(runs.createdAt)).limit(limit);
  } catch (err) {
    log.warn("listRuns failed", { error: (err as Error).message });
    return [];
  }
}

export async function getRun(id: string): Promise<Run | null> {
  try {
    const [row] = await db.select().from(runs).where(eq(runs.id, id)).limit(1);
    return row ?? null;
  } catch {
    return null;
  }
}

export async function deleteRun(id: string): Promise<boolean> {
  try {
    await db.delete(runs).where(eq(runs.id, id));
    return true;
  } catch {
    return false;
  }
}

const csvCell = (v: unknown) => {
  const s = v === null || v === undefined ? "" : typeof v === "object" ? JSON.stringify(v) : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function toCsv(rows: Array<Record<string, unknown>>): string {
  if (!rows.length) return "";
  const cols = Array.from(rows.reduce((set, r) => { Object.keys(r).forEach((k) => set.add(k)); return set; }, new Set<string>()));
  return [cols.join(","), ...rows.map((r) => cols.map((c) => csvCell(r[c])).join(","))].join("\n");
}

type AnyRec = Record<string, unknown>;

/** Flatten the run's main tabular output for CSV export. */
export function runToRows(run: Run): Array<Record<string, unknown>> {
  const out = run.output as AnyRec;
  switch (run.kind) {
    case "detection":
      return ((out.detections as AnyRec[]) ?? []).map((d) => ({ id: d.id, class: d.cls, confidence: d.confidence, x1: (d.bbox as number[])[0], y1: (d.bbox as number[])[1], x2: (d.bbox as number[])[2], y2: (d.bbox as number[])[3], cx: (d.centroid as number[])[0], cy: (d.centroid as number[])[1], snr: d.snr, area: d.area, elongation: d.elongation }));
    case "tracking":
      return ((out.tracks as AnyRec[]) ?? []).flatMap((t) => ((t.points as AnyRec[]) ?? []).map((p) => ({ track_id: t.id, kind: t.kind, confirmed: t.confirmed, frame: p.frame, x: p.x, y: p.y, measured: p.measured, speed_px_per_frame: t.speedPxPerFrame })));
    case "evaluation":
      return ((out.variants as AnyRec[]) ?? []).flatMap((v) => ((v.metrics as AnyRec).perClass as AnyRec[]).map((c) => ({ variant: v.variant, class: c.cls, gt: c.gt, tp: c.tp, fp: c.fp, fn: c.fn, precision: c.precision, recall: c.recall, f1: c.f1, ap: c.ap, ap50: c.ap50 })));
    case "propagation":
      return ((out.samples as AnyRec[]) ?? []).map((s) => ({ t: s.t, x_km: (s.position as AnyRec).x, y_km: (s.position as AnyRec).y, z_km: (s.position as AnyRec).z, vx_km_s: (s.velocity as AnyRec).x, vy_km_s: (s.velocity as AnyRec).y, vz_km_s: (s.velocity as AnyRec).z, lat_deg: s.latitudeDeg, lon_deg: s.longitudeDeg, alt_km: s.altitudeKm, speed_km_s: s.speedKmS }));
    case "conjunction":
      return ((out.series as AnyRec[]) ?? []).map((s) => ({ t: s.t, minutes: s.minutesFromStart, separation_km: s.separationKm, relative_speed_km_s: s.relativeSpeedKmS }));
    default:
      return [];
  }
}

/** Markdown research report: everything needed to understand and reproduce the run. */
export function runToMarkdown(run: Run): string {
  const demo = run.dataOrigin === "synthetic-demo";
  const lines = [
    `# ORBITAL GUARD run report — ${run.title}`,
    "",
    `- **Run id:** ${run.id}`,
    `- **Kind:** ${run.kind}`,
    `- **Created (UTC):** ${run.createdAt.toISOString()}`,
    `- **Data origin:** ${run.dataOrigin}${demo ? " (DEMONSTRATION DATA — not an experimental result)" : ""}`,
    `- **Model / method:** ${run.modelName ?? "n/a"} ${run.modelVersion ? `v${run.modelVersion}` : ""}`,
    "",
    "## Parameters",
    "```json", JSON.stringify(run.params, null, 2), "```",
    "## Input",
    "```json", JSON.stringify(run.input, null, 2), "```",
    "## Measured metrics / summary",
    "```json", JSON.stringify(run.metrics ?? {}, null, 2), "```",
    "## Limitations and assumptions",
    ...run.limitations.map((l) => `- ${l}`),
    "",
    "## Output (truncated to 200 rows in CSV form)",
    "```csv", toCsv(runToRows(run).slice(0, 200)), "```",
    "",
    `_Generated by ORBITAL GUARD at ${new Date().toISOString()}. Results are research-prototype outputs and must not be used for operational decisions._`,
  ];
  return lines.join("\n");
}

export function runToCsv(run: Run): string {
  const rows = runToRows(run);
  return rows.length ? toCsv(rows) : toCsv([{ note: "no tabular output for this run", kind: run.kind, id: run.id }]);
}
